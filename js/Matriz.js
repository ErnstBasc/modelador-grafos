class Matriz {

    constructor(
        grafo
    ) {

        // ==================================
        // REFERENCIA AL GRAFO
        // ==================================

        this.grafo = grafo;


        // ==================================
        // MATRIZ
        // ==================================


        this.datos = [];

        // ==================================
        // ORDEN DE LOS NODOS
        // ==================================



        this.nodos = [];
    }


    // ==========================================
    // PREPARAR MATRIZ
    // ==========================================

    preparar() {

        this.nodos =
            this.grafo.obtenerNodos();


        this.datos = [];
    }


    // ==========================================
    // OBTENER MATRIZ
    // ==========================================

    obtenerDatos() {

        return this.datos;
    }


    // ==========================================
    // OBTENER NODOS
    // ==========================================

    obtenerNodos() {

        return this.nodos;
    }


    // ==========================================
    // LIMPIAR MATRIZ
    // ==========================================

    limpiar() {

        this.datos = [];

        this.nodos = [];
    }
}